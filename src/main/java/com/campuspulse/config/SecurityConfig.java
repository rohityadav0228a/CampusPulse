package com.campuspulse.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.config.annotation.web.configuration.EnableWebSecurity;
import org.springframework.security.config.http.SessionCreationPolicy;
import org.springframework.security.core.userdetails.User;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.security.core.userdetails.UserDetailsService;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.security.provisioning.InMemoryUserDetailsManager;
import org.springframework.security.web.SecurityFilterChain;

import java.util.UUID;

/**
 * Spring Security configuration for CampusPulse.
 * Configures role-based access control, BCrypt password hashing, session management,
 * and public route exemptions.
 */
@Configuration
@EnableWebSecurity
public class SecurityConfig {

    private static final Logger log = LoggerFactory.getLogger(SecurityConfig.class);

    @Value("${campuspulse.admin.username:admin}")
    private String adminUsername;

    @Value("${campuspulse.admin.password:}")
    private String adminPassword;

    @Value("${campuspulse.admin.password-hash:}")
    private String adminPasswordHash;

    /**
     * Password encoder using BCrypt strong hashing algorithm.
     *
     * @return BCryptPasswordEncoder instance
     */
    @Bean
    public PasswordEncoder passwordEncoder() {
        return new BCryptPasswordEncoder();
    }

    /**
     * UserDetailsService bean configured with administrative credentials from environment
     * variables. Credentials are never hardcoded.
     *
     * @param passwordEncoder the BCrypt encoder bean
     * @return UserDetailsService with configured admin user
     */
    @Bean
    public UserDetailsService userDetailsService(PasswordEncoder passwordEncoder) {
        String encodedPassword;
        if (adminPasswordHash != null && !adminPasswordHash.isBlank()) {
            encodedPassword = adminPasswordHash.trim();
        } else if (adminPassword != null && !adminPassword.isBlank()) {
            encodedPassword = passwordEncoder.encode(adminPassword.trim());
        } else {
            // Cryptographically secure one-time password generated when environment variable is not supplied
            String autoGenerated = UUID.randomUUID().toString();
            encodedPassword = passwordEncoder.encode(autoGenerated);
            log.warn("=================================================================");
            log.warn("Notice: No ADMIN_PASSWORD or ADMIN_PASSWORD_HASH set in environment.");
            log.warn("Generated temporary startup admin credentials:");
            log.warn("Username: {}", adminUsername);
            log.warn("Password: {}", autoGenerated);
            log.warn("To configure permanent credentials, export ADMIN_PASSWORD in your environment.");
            log.warn("=================================================================");
        }

        UserDetails admin = User.builder()
                .username(adminUsername)
                .password(encodedPassword)
                .roles("ADMIN")
                .build();

        return new InMemoryUserDetailsManager(admin);
    }

    /**
     * Security filter chain defining authorization rules, custom login page,
     * logout handling, and CSRF protection.
     *
     * @param http HttpSecurity configuration builder
     * @return built SecurityFilterChain
     * @throws Exception if security configuration fails
     */
    @Bean
    public SecurityFilterChain securityFilterChain(HttpSecurity http) throws Exception {
        http
                .authorizeHttpRequests(authorize -> authorize
                        // Protect administrative endpoints with ADMIN role
                        .requestMatchers("/admin/**").hasRole("ADMIN")
                        // Allow public access to landing page, static assets, and student workflows
                        .requestMatchers(
                                "/",
                                "/css/**",
                                "/js/**",
                                "/images/**",
                                "/favicon.ico",
                                "/complaints",
                                "/complaints/new",
                                "/complaints/suggest-category",
                                "/complaints/track",
                                "/complaints/success/**",
                                "/login"
                        ).permitAll()
                        // Any remaining request requires authentication
                        .anyRequest().authenticated()
                )
                .formLogin(form -> form
                        .loginPage("/login")
                        .loginProcessingUrl("/login")
                        .defaultSuccessUrl("/admin/complaints", true)
                        .failureUrl("/login?error=true")
                        .permitAll()
                )
                .logout(logout -> logout
                        .logoutUrl("/logout")
                        .logoutSuccessUrl("/login?logout=true")
                        .invalidateHttpSession(true)
                        .deleteCookies("JSESSIONID")
                        .permitAll()
                )
                .sessionManagement(session -> session
                        .sessionCreationPolicy(SessionCreationPolicy.IF_REQUIRED)
                );

        return http.build();
    }
}
